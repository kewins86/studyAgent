    /**
     * 识别学科
     *
     * @param question 学生问题
     * @return 学科名；识别不出返回 "综合"
     */

    /**
     * 仅关键词检测（不调 LLM），返回 null 表示未命中
     */
    public String classifyByKeyword(String question) {
        // 正则快速匹配：纯算式（如 25+17、3×4、56÷7）
        if (question.matches(".*\\d+\\s*[+\\-×÷*\\/].*") || question.matches(".*[+\\-×÷*\\/]\\s*\\d+.*")) {
            return "数学";
        }
        for (Map.Entry<String, String[]> entry : KEYWORDS.entrySet()) {
            for (String kw : entry.getValue()) {
                if (question.contains(kw)) {
                    return entry.getKey();
                }
            }
        }
        return null;
    }
    public String classify(String question) {
    // 第一层：关键词规则（复用 classifyByKeyword，含正则匹配）
    String kwResult = classifyByKeyword(question);
    if (kwResult != null) {
        return kwResult;
    }
        // 第二层：LLM few-shot 兜底
        try {
            String prompt = """
                    你是学科分类器。判断以下学生问题属于哪个学科，只输出JSON：
                    {"subject": "学科名"}
                    可选学科：语文、数学、英语、物理、化学、生物、历史、地理、政治
                    注意：小学题目（加减乘除、应用题、口算、竖式、图形等）属于数学；识字、组词、造句、课文属于语文。
                    示例：
                    Q: 25+17等于多少？ -> {"subject": "数学"}
                    Q: 小红有5个苹果，吃了2个，还剩几个？ -> {"subject": "数学"}
                    Q: "大"字的笔顺是什么？ -> {"subject": "语文"}
                    Q: 春眠不觉晓下一句是什么？ -> {"subject": "语文"}
                    现在的问题：%s
                    """.formatted(question);
            JsonNode node = llmClient.chatJson("你是严谨的学科分类器", prompt);
            if (node != null && node.has("subject")) {
                return node.get("subject").asText();
            }
        } catch (Exception e) {
            log.warn("LLM 学科分类失败，回退综合: {}", e.getMessage());
        }
        return "综合";
    }

